// Generates app/src/core/vial-keycode-tables.js from a vitaly checkout so the
// web shell names keycodes exactly like the desktop shell (vitaly, MIT).
//
//   node scripts/generate-vial-keycodes.mjs <path-to-vitaly>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const vitaly = process.argv[2];
if (!vitaly) {
  console.error('usage: node scripts/generate-vial-keycodes.mjs <path-to-vitaly>');
  process.exit(1);
}
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(repoRoot, 'app', 'src', 'core', 'vial-keycode-tables.js');

function fullnamesSection(file) {
  const text = fs.readFileSync(file, 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/.*$/gm, '');
  const start = text.indexOf('pub static FULLNAMES');
  if (start < 0) throw new Error(`FULLNAMES not found in ${file}`);
  return text.slice(start);
}

function readVersion(version) {
  const dir = path.join(vitaly, 'src', 'keycodes', version);
  const codeToName = new Map();
  for (const [, code, name] of fullnamesSection(path.join(dir, 'code_to_name.rs'))
    .matchAll(/m\.insert\(\s*(0x[0-9A-Fa-f]+|[0-9]+)\s*,\s*"([^"]+)"\s*\)/g)) {
    codeToName.set(Number(code), name);
  }
  const nameToCode = new Map();
  const section = fullnamesSection(path.join(dir, 'name_to_code.rs'));
  for (const [, name, code, alias] of section
    .matchAll(/m\.insert\(\s*"([^"]+)"\s*,\s*(?:(0x[0-9A-Fa-f]+|[0-9]+)|\*m\.get\("([^"]+)"\)\.unwrap\(\))\s*,?\s*\)/g)) {
    const value = code !== undefined ? Number(code) : nameToCode.get(alias);
    if (value === undefined) throw new Error(`${version}: alias ${name} -> ${alias} is unresolved`);
    nameToCode.set(name, value);
  }
  // Only names that the reverse of codeToName does not already provide.
  const aliases = {};
  for (const [name, code] of nameToCode) {
    if (codeToName.get(code) !== name) aliases[name] = code;
  }
  return { names: Object.fromEntries([...codeToName].sort((a, b) => a[0] - b[0])), aliases };
}

const hex = (value) => `0x${value.toString(16).padStart(4, '0')}`;
function emit(name, table) {
  const names = Object.entries(table.names).map(([code, value]) => `  [${hex(Number(code))}, ${JSON.stringify(value)}],`);
  const aliases = Object.entries(table.aliases).map(([alias, code]) => `  ${JSON.stringify(alias)}: ${hex(code)},`);
  return `const ${name}_NAMES = [\n${names.join('\n')}\n];\n\nconst ${name}_ALIASES = {\n${aliases.join('\n')}\n};\n`;
}

const header = `/* Generated by scripts/generate-vial-keycodes.mjs — do not edit.
 *
 * Keycode name tables for Vial protocol v5 and v6 (QMK keycodes before and
 * after the 2022 renumbering). Taken from vitaly (https://github.com/bskaplou/vitaly,
 * MIT License, Copyright (c) 2025 Boris Kaplunovsky) so the web shell writes
 * the same names as the desktop shell.
 */
`;
const body = [emit('V5', readVersion('v5')), emit('V6', readVersion('v6'))].join('\n');
fs.writeFileSync(out, `${header}\n${body}\nexport { V5_NAMES, V5_ALIASES, V6_NAMES, V6_ALIASES };\n`);
console.log(`wrote ${path.relative(repoRoot, out)}`);
